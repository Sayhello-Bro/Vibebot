def to_traditional_chinese(text: str) -> str:
    result = str(text or "")
    for simplified, traditional in COMMON_PHRASE_MAP:
        result = result.replace(simplified, traditional)

    translated_chars = []
    for ch in result:
        translated_chars.append(CHAR_MAP.get(ch, ch))
    return "".join(translated_chars)

